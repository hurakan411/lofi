import Foundation

struct CollectionStory: Equatable {
    struct Chapter: Identifiable, Equatable {
        let rank: Int
        let title: String
        let text: String
        var id: Int { rank }
    }

    var world: FocusWorld = .rooftop
    let title: String
    private let chapters: [Chapter]

    /// The reader uses this gate for titles as well as chapter text.
    func chapter(at rank: Int, unlockedRank: Int) -> Chapter? {
        guard rank >= 1, rank <= min(5, unlockedRank) else { return nil }
        return chapters.first { $0.rank == rank }
    }

