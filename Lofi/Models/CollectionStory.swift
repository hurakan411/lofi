        「ひとつだけ、お願いしてもいいですか」

        どこかで声がした。
        少し間を置いて、別の声が答える。

        「ひとつなら。順番に、どうぞ」
        """),
        .init(rank: 2, title: "小さな申請", text: """
        狐の面の女の子は、申請書を帳面に写していた。
